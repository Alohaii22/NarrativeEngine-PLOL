#!/usr/bin/env node
/**
 * Builds NarrativeEngine.mcpb: a Claude Desktop extension (MCP Bundle) that
 * runs this folder's MCP server (server/mcp). Double-click the file and
 * Claude Desktop shows an Install screen; the extension then lives under
 * Settings > Desktop app > Extensions.
 *
 * The bundle is a thin launcher. It starts server/mcp/index.js from this
 * folder with the Node.js that installed it (the one `npm install` built the
 * engine's native modules for), and logs to server/mcp/.cache/mcp.log so a
 * failure can be read without digging through Claude's settings.
 *
 * Usage: node scripts/build-mcpb.mjs [--out <file>]
 */
import fs from 'fs';
import os from 'os';
import path from 'path';
import zlib from 'zlib';
import { fileURLToPath } from 'url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf-8'));

/**
 * Where the last Play_With_Claude run says this install lives. The extension
 * falls back to it when its own folder setting is stale, so moving the folder
 * and running Play_With_Claude again is enough: no reinstall, no settings.
 */
export const POINTER_FILE = path.join(os.homedir(), '.narrative-engine', 'install.json');

export function writeInstallPointer({ folder = REPO_ROOT, nodePath = process.execPath, file = POINTER_FILE } = {}) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify({ folder, node: nodePath, updatedAt: new Date().toISOString() }, null, 2));
    return file;
}

// Runs under Claude Desktop's own Node.js, so plain CommonJS with no dependencies.
export const LAUNCHER = `'use strict';
// Narrative Engine desktop extension launcher (generated by scripts/build-mcpb.mjs).
const { spawn, execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const home = path.join(os.homedir(), '.narrative-engine');
const isInstall = (dir) => !!dir && fs.existsSync(path.join(dir, 'server', 'mcp', 'index.js'));
let pointer = {};
try { pointer = JSON.parse(fs.readFileSync(process.env.NE_POINTER_FILE || path.join(home, 'install.json'), 'utf8')); } catch (e) { /* Play_With_Claude has not run yet */ }

// The folder set in the extension wins; if it is gone (moved, renamed), use
// the one Play_With_Claude last ran from.
const configured = process.env.NE_FOLDER || '';
const folder = isInstall(configured) ? configured : isInstall(pointer.folder) ? pointer.folder : '';
const logDir = folder ? path.join(folder, 'server', 'mcp', '.cache') : home;
let log = null;
try { fs.mkdirSync(logDir, { recursive: true }); log = fs.openSync(path.join(logDir, 'mcp.log'), 'a'); } catch (e) { /* log to stderr only */ }
const write = (text) => { process.stderr.write(text); if (log !== null) { try { fs.writeSync(log, text); } catch (e) { /* disk full etc. */ } } };
const note = (msg) => write('[' + new Date().toISOString() + '] ' + msg + '\\n');
const stop = (msg) => { note(msg); process.exit(1); };

if (!folder) {
  stop('Narrative Engine folder not found: "' + configured + '". Double-click Play_With_Claude.bat in your Narrative Engine folder once (it tells Claude where the folder is), then turn this extension off and on. Or choose the folder yourself in Settings > Desktop app > Extensions (Manage) > Narrative Engine.');
}
if (folder !== configured) note('The folder set in the extension ("' + configured + '") is gone; using ' + folder);
if (!fs.existsSync(path.join(folder, 'node_modules', '@modelcontextprotocol', 'sdk'))) {
  stop('Narrative Engine is not installed yet in ' + folder + '. Double-click Play_With_Claude.bat there once and let it finish, then turn this extension off and on.');
}

// Use the Node.js that installed Narrative Engine (its native modules were
// built for it); then whatever "node" is on PATH; Claude's own Node last.
function onPath() {
  try { return execFileSync(process.platform === 'win32' ? 'where' : 'which', ['node'], { encoding: 'utf8', windowsHide: true }).split(/\\r?\\n/)[0].trim(); } catch (e) { return ''; }
}
const node = [process.env.NE_NODE, pointer.node, onPath()].find((p) => p && fs.existsSync(p)) || process.execPath;
let version = '';
try { version = execFileSync(node, ['-p', 'process.versions.node'], { encoding: 'utf8', windowsHide: true, env: Object.assign({}, process.env, { ELECTRON_RUN_AS_NODE: '1' }) }).trim(); } catch (e) { /* reported by the spawn below */ }
const parts = version.split('.').map(Number);
if (version && (parts[0] < 20 || (parts[0] === 20 && parts[1] < 19))) {
  stop('Node.js ' + version + ' (' + node + ') is too old: Narrative Engine needs 20.19 or newer. Install the LTS version from https://nodejs.org, then double-click Play_With_Claude.bat again.');
}

const entry = path.join(folder, 'server', 'mcp', 'index.js');
note('Starting ' + entry + ' with ' + node + (version ? ' (Node ' + version + ')' : ''));
const child = spawn(node, [entry], {
  cwd: folder,
  stdio: ['inherit', 'inherit', 'pipe'],
  env: Object.assign({}, process.env, { NE_LAUNCHED_BY: 'mcpb', ELECTRON_RUN_AS_NODE: '1' }),
  windowsHide: true,
});
child.stderr.on('data', (d) => write(String(d)));
child.on('error', (err) => stop('Could not start the MCP server: ' + err.message));
child.on('exit', (code, signal) => { note('MCP server exited (' + (signal || code) + ')'); process.exit(code == null ? 1 : code); });
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => child.kill(sig));
`;

