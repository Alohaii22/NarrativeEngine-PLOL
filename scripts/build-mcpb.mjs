// ── Minimal zip writer (deflate) ─────────────────────────────────────────
const CRC_TABLE = (() => {
    const t = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
        let c = n;
        for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
        t[n] = c >>> 0;
    }
    return t;
})();
function crc32(buf) {
    let c = 0xffffffff;
    for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
}

export function zip(files) {
    const locals = [];
    const centrals = [];
    let offset = 0;
    for (const { name, data } of files) {
        const raw = Buffer.isBuffer(data) ? data : Buffer.from(data);
        const deflated = zlib.deflateRawSync(raw);
        const nameBuf = Buffer.from(name, 'utf-8');
        const crc = crc32(raw);
        const local = Buffer.alloc(30);
        local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
        local.writeUInt16LE(8, 8); local.writeUInt32LE(0, 10); local.writeUInt32LE(crc, 14);
        local.writeUInt32LE(deflated.length, 18); local.writeUInt32LE(raw.length, 22);
        local.writeUInt16LE(nameBuf.length, 26); local.writeUInt16LE(0, 28);
        locals.push(local, nameBuf, deflated);
        const central = Buffer.alloc(46);
        central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6);
        central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10); central.writeUInt32LE(0, 12);
        central.writeUInt32LE(crc, 16); central.writeUInt32LE(deflated.length, 20); central.writeUInt32LE(raw.length, 24);
        central.writeUInt16LE(nameBuf.length, 28); central.writeUInt32LE(offset, 42);
        centrals.push(central, nameBuf);
        offset += 30 + nameBuf.length + deflated.length;
    }
    const centralSize = centrals.reduce((n, b) => n + b.length, 0);
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10);
    end.writeUInt32LE(centralSize, 12); end.writeUInt32LE(offset, 16);
    return Buffer.concat([...locals, ...centrals, end]);
}

export function buildBundle(options = {}) {
    const files = [
        { name: 'manifest.json', data: JSON.stringify(buildManifest(options), null, 2) },
        { name: 'server/index.js', data: LAUNCHER },
    ];
    const icon = path.join(REPO_ROOT, 'public', 'branding', 'narrative-engine-512.png');
    if (fs.existsSync(icon)) files.push({ name: 'icon.png', data: fs.readFileSync(icon) });
    return zip(files);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const outIdx = process.argv.indexOf('--out');
    const out = outIdx > 0 ? path.resolve(process.argv[outIdx + 1]) : path.join(REPO_ROOT, 'NarrativeEngine.mcpb');
    fs.writeFileSync(out, buildBundle());
    console.log(`Built ${out}`);
}
