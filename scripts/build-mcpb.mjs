#!/usr/bin/env node
/**
 * Builds NarrativeEngine.mcpb: a Claude Desktop extension (MCP Bundle) that
 * runs this folder's MCP server (server/mcp). Double-click the file and
 * Claude Desktop shows an Install screen; the extension then lives under
 * Settings > Desktop app > Extensions.
 *
 * The bundle is a thin launcher. It starts server/mcp/index.js from this
 * folder with the Node.js that installed it (the one `npm install` built the
 * engine's native modules for), and logs to server/mcp/.cache/mcp.log so a
 * failure can be read without digging through Claude's settings.
 *
 * Usage: node scripts/build-mcpb.mjs [--out <file>]
 */
import fs from 'fs';
import path from 'path';
import zlib from 'zlib';
import { fileURLToPath } from 'url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf-8'));

// Runs under Claude Desktop's own Node.js, so plain CommonJS with no dependencies.
export const LAUNCHER = `'use strict';
// Narrative Engine desktop extension launcher (generated by scripts/build-mcpb.mjs).
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const folder = process.env.NE_FOLDER || '';
const entry = path.join(folder, 'server', 'mcp', 'index.js');
const logDir = path.join(folder, 'server', 'mcp', '.cache');
let log = null;
try { fs.mkdirSync(logDir, { recursive: true }); log = fs.createWriteStream(path.join(logDir, 'mcp.log'), { flags: 'a' }); } catch (e) { /* folder missing; reported below */ }
const note = (msg) => { const line = '[' + new Date().toISOString() + '] ' + msg + '\\n'; process.stderr.write(line); if (log) log.write(line); };

if (!folder || !fs.existsSync(entry)) {
  note('Narrative Engine folder not found: "' + folder + '". Open Settings > Desktop app > Extensions (Manage) > Narrative Engine and choose the folder that contains Play_With_Claude.bat.');
  process.exit(1);
}

const preferred = process.env.NE_NODE;
const node = preferred && fs.existsSync(preferred) ? preferred : process.execPath;
note('Starting ' + entry + ' with ' + node);
const child = spawn(node, [entry], {
  cwd: folder,
  stdio: ['inherit', 'inherit', 'pipe'],
  env: Object.assign({}, process.env, { NE_LAUNCHED_BY: 'mcpb' }),
  windowsHide: true,
});
child.stderr.on('data', (d) => { process.stderr.write(d); if (log) log.write(d); });
child.on('error', (err) => { note('Could not start the MCP server: ' + err.message); process.exit(1); });
child.on('exit', (code, signal) => { note('MCP server exited (' + (signal || code) + ')'); process.exit(code == null ? 1 : code); });
for (const sig of ['SIGINT', 'SIGTERM']) process.on(sig, () => child.kill(sig));
`;

